test('我的身份失败显示重试按钮：实际点击重新同意启用，离线开关仍能撤回', async () => {
  jest.useFakeTimers(); runtime();
  wx.showModal = jest.fn(); wx.showToast = jest.fn();
  let definition;
  global.Page = p => { definition = p; };
  require('../pages/me/me');
  const page = { ...definition, data: { ...definition.data }, setData(p) { Object.assign(this.data, p); } };
  await page.onShow();
  wx.cloud.callFunction.mockRejectedValueOnce(Error('login failed'));
  page.onToggleOffline({ detail: { value: false } });
  await wx.showModal.mock.calls[0][0].success({ confirm: true });
  await page.onShow();
  expect(page.data.offlineMode).toBe(false);
  const wxml = require('fs').readFileSync(require('path').join(__dirname, '../pages/me/me.wxml'), 'utf8');
  const button = wxml.match(/<button\b[^>]*>重试云服务<\/button>/);
  expect(button).not.toBeNull();
  const condition = button[0].match(/wx:if="{{(\w+)}}"/)[1];
  const handler = button[0].match(/bindtap="(\w+)"/)[1];
  expect(page.data[condition]).toBe(true);
  expect(wx.showToast.mock.calls.at(-1)[0].title).toContain('重试云服务');
  page[handler]({ type: 'tap', currentTarget: { dataset: {} } });
  await wx.showModal.mock.calls[1][0].success({ confirm: false });
  expect(page.data.offlineMode).toBe(false);
  expect(page.data[condition]).toBe(true);
  page[handler]({ type: 'tap', detail: {}, currentTarget: { dataset: {} } });
  await wx.showModal.mock.calls[2][0].success({ confirm: true });
  expect(page.data.openid).toBe('A');
  expect(page.data[condition]).toBe(false);
  page.onToggleOffline({ detail: { value: true } });
  wx.cloud.callFunction.mockRejectedValueOnce(Error('login failed again'));
  page.onToggleOffline({ detail: { value: false } });
  await wx.showModal.mock.calls[3][0].success({ confirm: true });
  expect(page.data[condition]).toBe(true);
  page.onToggleOffline({ detail: { value: true } });
  expect(page.data.offlineMode).toBe(true);
  expect(page.data[condition]).toBe(false);
  expect(require('../utils/cloud-service').snapshot().consent).toBe(false);
});
